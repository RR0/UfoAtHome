/**
 * One-off build step (not part of `build`) that turns the IGRF's coefficient table into src/engine/astronomy/igrfCoefficients.ts: the
 * Earth's main field every five years since 1900, which Igrf evaluates and traces (see Igrf.apexLatitude).
 *
 * Run with: npm run build:igrf [igrf14coeffs.txt]
 * (default: scripts/data/igrf/igrf14coeffs.txt, from https://www.ngdc.noaa.gov/IAGA/vmod/coeffs/igrf14coeffs.txt — the IAGA's
 * International Geomagnetic Reference Field, 14th generation, free to use with credit).
 */
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

class IgrfBuild {
  private static readonly ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
  private static readonly OUT = path.join(IgrfBuild.ROOT, "src", "engine", "astronomy", "igrfCoefficients.ts")

  static run(source = path.join(IgrfBuild.ROOT, "scripts", "data", "igrf", "igrf14coeffs.txt")): void {
    const lines = readFileSync(source, "utf8").split("\n").filter(line => line.trim() && !line.startsWith("#"))
    const header = lines.find(line => line.startsWith("g/h"))!.trim().split(/\s+/)
    // "g/h n m 1900.0 … 2025.0 2025-30": the epochs, then the secular variation of the last.
    const epochs = header.slice(3, -1).map(Number)
    const terms: [string, number, number][] = []
    const values: number[][] = epochs.map(() => [])
    const variation: number[] = []
    for (const line of lines) {
      const cells = line.trim().split(/\s+/)
      if (cells[0] !== "g" && cells[0] !== "h") continue
      terms.push([cells[0], Number(cells[1]), Number(cells[2])])
      epochs.forEach((_, index) => values[index].push(Number(cells[3 + index])))
      variation.push(Number(cells[3 + epochs.length]))
    }
    const text = `// Generated by scripts/build-igrf.ts from the IAGA's IGRF-14 (https://www.ngdc.noaa.gov/IAGA/vmod/igrf.html). Do not edit.

/** The epochs the coefficients are given at, years. */
export const IGRF_EPOCHS: readonly number[] = ${JSON.stringify(epochs)}

/** Each coefficient's kind and degree: [g or h, n, m], in the order every epoch's values are listed. */
export const IGRF_TERMS: readonly (readonly ["g" | "h", number, number])[] = ${JSON.stringify(terms)}

/** The Schmidt semi-normalised coefficients, nT, one row per epoch: 0 where an epoch has no term of that degree (before 2000, n > 10). */
export const IGRF_VALUES: readonly (readonly number[])[] = [
${values.map(row => "  " + JSON.stringify(row)).join(",\n")}
]

/** How the last epoch's coefficients change, nT a year, for the five years after it. */
export const IGRF_VARIATION: readonly number[] = ${JSON.stringify(variation)}
`
    writeFileSync(IgrfBuild.OUT, text)
    console.log(`${terms.length} terms, ${epochs.length} epochs → ${path.relative(IgrfBuild.ROOT, IgrfBuild.OUT)}`)
  }
}

IgrfBuild.run(process.argv[2])
